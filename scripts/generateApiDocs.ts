import * as fs from 'fs';
import * as path from 'path';

console.log("[API-DOCS] Generating API documentation...");
const docsDir = path.join(process.cwd(), 'docs');
const docsFile = path.join(docsDir, 'api-reference.md');

const isDryRun = process.env.DRY_RUN !== 'false';

const routesDir = path.join(process.cwd(), 'src/routes');
let endpointsFound = 0;
let markdown = `# API Reference\n\n*Generated by generateApiDocs.ts*\n\n`;

if (fs.existsSync(routesDir)) {
    const files = fs.readdirSync(routesDir);
    for (const file of files) {
        if (file.endsWith('.ts')) {
            const content = fs.readFileSync(path.join(routesDir, file), 'utf8');
            const matches = content.match(/router\.(get|post|put|delete|patch)\(['"]([^'"]+)['"]/g);
            if (matches) {
                markdown += `## ${file}\n`;
                matches.forEach(m => {
                    endpointsFound++;
                    markdown += `- \`${m.replace('router.', '').replace(/['"]/g, '')}\`\n`;
                });
                markdown += `\n`;
            }
        }
    }
}

if (endpointsFound === 0) {
    markdown += `No explicit router endpoints found in src/routes.\n`;
}

markdown += `\n**Security Note:** Financial endpoints require server-side authority. Client-provided balances or PINs must be cryptographically verified against backend sources of truth.\n`;

if (isDryRun) {
    console.log(`[API-DOCS] DRY RUN — Found ${endpointsFound} endpoints. NO FILE WRITTEN.`);
    process.exit(0);
}

if (!fs.existsSync(docsDir)) {
    fs.mkdirSync(docsDir, { recursive: true });
}

fs.writeFileSync(docsFile, markdown);
console.log(`[API-DOCS] API Documentation generated successfully at ${docsFile} with ${endpointsFound} endpoints.`);
process.exit(0);
